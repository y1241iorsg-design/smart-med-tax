def detect_severe_symptom(text: str) -> bool:
    return any(kw in text for kw in SEVERE_KEYWORDS)


def match_categories_from_text(text: str) -> list[str]:
    matched: list[str] = []
    for category, triggers in CATEGORY_CHAT_TRIGGERS.items():
        if any(trigger in text for trigger in triggers):
            matched.append(category)
    return matched
